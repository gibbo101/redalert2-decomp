PATCHED_ADDRESSES = {**MAP_LIGHT, **STATIC_LIGHT_ADDRESSES}

def static_light_profile(data, *, allow_patched=False):
    return map_light_profile(data, allow_patched=allow_patched)

def address(profile, disc_va):
    if profile == "allied-disc":
        return disc_va
    if profile == "supplied-ra2-1006":
        try:
            return PATCHED_ADDRESSES[disc_va]
        except KeyError as error:
            raise ValueError(f"Unmapped 1.006 static-light address {disc_va:#x}") from error
    raise ValueError("Unknown static-light profile")
