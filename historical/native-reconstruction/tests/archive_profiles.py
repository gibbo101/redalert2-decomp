def archive_profile(data):
    digest = hashlib.sha256(data).hexdigest()
    if digest == EXPECTED: return digest, 'allied-disc'
    if digest == PATCHED_EXPECTED: return digest, 'supplied-ra2-1006'
    raise ValueError('Unsupported archive executable SHA-256')


def address(profile, disc_va):
    if profile == 'allied-disc': return disc_va
    if profile != 'supplied-ra2-1006': raise ValueError('Unknown archive profile')
    if disc_va not in PATCHED_ADDRESSES: raise ValueError(f'Unmapped archive address {disc_va:#x}')
    return PATCHED_ADDRESSES[disc_va]
