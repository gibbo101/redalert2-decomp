PATCHED_ADDRESSES = {**COMPOSITION, **SHADOW_COLOR_ADDRESSES}

def shadow_color_profile(data, *, allow_patched=False):
    return composition_profile(data, allow_patched=allow_patched)

def address(profile, disc_va):
    if profile == "allied-disc":
        return disc_va
    if profile == "supplied-ra2-1006":
        try:
            return PATCHED_ADDRESSES[disc_va]
        except KeyError as error:
            raise ValueError(f"Unmapped 1.006 shadow/color address {disc_va:#x}") from error
    raise ValueError("Unknown shadow/color profile")
