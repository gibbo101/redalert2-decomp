#!/usr/bin/env python3
"""Regenerate the unit table of docs/RECOVERED_SOURCE_INDEX.md from the catalog.

Accepted sources are grouped by their directory under src/recovered/ (one
class or family per directory; address-named discovery files directly under
src/recovered/ form one group). For each group the table lists accepted
regions, matched body bytes, how many carry a descriptive (non-address)
filename, and the address range. Only the text between the
`<!-- generated:units -->` markers is replaced; the catalog stays the
authority for every path, symbol and hash.
"""
from collections import defaultdict
import catalog_io
import json
from pathlib import Path
import re

REPOSITORY = Path(__file__).resolve().parents[2]
INDEX = REPOSITORY / 'docs/RECOVERED_SOURCE_INDEX.md'
START, END = '<!-- generated:units -->', '<!-- /generated:units -->'
ADDRESS_ONLY = re.compile(r'^[0-9a-f]{8}\.cpp$')


def main():
    catalog = catalog_io.load(catalog_io.locate(REPOSITORY), references=False)
    groups = defaultdict(list)
    for row in catalog['regions']:
        path = Path(row['source'])
        parts = path.relative_to('src/recovered').parts
        groups['/'.join(parts[:-1]) or '(discovery: address-named)'].append(row)
    lines = [START, '',
             '| Directory under `src/recovered/` | Regions | Body bytes | Descriptive names | Address range |',
             '| --- | ---: | ---: | ---: | --- |']
    for name, rows in sorted(groups.items(), key=lambda kv: (-sum(r['body_bytes'] for r in kv[1]), kv[0])):
        named = sum(1 for r in rows if not ADDRESS_ONLY.match(Path(r['source']).name))
        lines.append('| %s | %d | %s | %d | 0x%08X–0x%08X |' % (
            name if name.startswith('(') else '[%s](../src/recovered/%s/)' % (name, name), len(rows),
            format(sum(r['body_bytes'] for r in rows), ','), named,
            min(r['entry'] for r in rows), max(r['entry'] for r in rows)))
    lines += ['', '%d directories, %d regions. Generated by `tools/original_target/source_index.py`.' % (
        len(groups), len(catalog['regions'])), '', END]
    text = INDEX.read_text()
    block = '\n'.join(lines)
    if START in text:
        text = text[:text.index(START)] + block + text[text.index(END) + len(END):]
    else:
        heading = text.index('\n', text.index('# ')) + 1
        text = text[:heading] + '\n## Units by directory\n\n' + block + '\n' + text[heading:]
    INDEX.write_text(text)
    print(INDEX)


if __name__ == '__main__':
    main()
